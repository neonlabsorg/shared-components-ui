/*
 *
 * Web Components use only plain strings as props
 *
 * */

const DEFAULTS = {
  title: "Something went wrong",
  description: "Sorry, you are not allowed to be here",
  imgUrl:
    "https://placehold.jp/ffffff/f549b4/600x400.png?text=Something%20went%20wrong",
  redirectUrl: "/",
  classList: "not-found_wrapper",
};

/**
 * Usage:
 *
 *  <stub-not-found></stub-not-found>
 *
 */
class StubNotFound extends HTMLElement {
  get _root() {
    return this.shadowRoot || this;
  }

  constructor() {
    super();
    const self = this;

    this.state = {};
    if (!this.props) {
      this.props = {};
    }

    this.componentProps = ["classList", "redirectUrl", "imgUrl", "title"];

    // used to keep track of all nodes created by show/for
    this.nodesToDestroy = [];
    // batch updates
    this.pendingUpdate = false;

    if (undefined) {
      this.attachShadow({ mode: "open" });
    }
  }

  destroyAnyNodes() {
    // destroy current view template refs before rendering again
    this.nodesToDestroy.forEach((el) => el.remove());
    this.nodesToDestroy = [];
  }

  connectedCallback() {
    this.getAttributeNames().forEach((attr) => {
      const jsVar = attr.replace(/-/g, "");
      const regexp = new RegExp(jsVar, "i");
      this.componentProps.forEach((prop) => {
        if (regexp.test(prop)) {
          const attrValue = this.getAttribute(attr);
          if (this.props[prop] !== attrValue) {
            this.props[prop] = attrValue;
          }
        }
      });
    });

    this._root.innerHTML = `
      <div data-el="div-stub-not-found-1">
        <a class="a-stub-not-found" data-el="a-stub-not-found-1">
          <img data-el="img-stub-not-found-1" />
        </a>
      </div>
      <style>
        .div-stub-not-found {
          width: 100%;
          height: 100%;
          display: grid;
          place-items: center;
        }
        .a-stub-not-found {
          color: inherit;
          text-decoration: none;
        }
      </style>`;
    this.pendingUpdate = true;

    this.render();
    this.onMount();
    this.pendingUpdate = false;
    this.update();
  }

  onMount() {}

  onUpdate() {}

  update() {
    if (this.pendingUpdate === true) {
      return;
    }
    this.pendingUpdate = true;
    this.render();
    this.onUpdate();
    this.pendingUpdate = false;
  }

  render() {
    // re-rendering needs to ensure that all nodes generated by for/show are refreshed
    this.destroyAnyNodes();
    this.updateBindings();
  }

  updateBindings() {
    this._root
      .querySelectorAll("[data-el='div-stub-not-found-1']")
      .forEach((el) => {
        el.className =
          this.props.classList || DEFAULTS.classList + " div-stub-not-found";
      });

    this._root
      .querySelectorAll("[data-el='a-stub-not-found-1']")
      .forEach((el) => {
        el.setAttribute("href", this.props.redirectUrl || DEFAULTS.redirectUrl);
      });

    this._root
      .querySelectorAll("[data-el='img-stub-not-found-1']")
      .forEach((el) => {
        el.setAttribute("src", this.props.imgUrl || DEFAULTS.imgUrl);
        el.setAttribute("alt", this.props.title || DEFAULTS.title);
      });
  }

  // Helper to render content
  renderTextNode(el, text) {
    const textNode = document.createTextNode(text);
    if (el?.scope) {
      textNode.scope = el.scope;
    }
    if (el?.context) {
      textNode.context = el.context;
    }
    el.after(textNode);
    this.nodesToDestroy.push(el.nextSibling);
  }
}

customElements.define("stub-not-found", StubNotFound);
